"""Load January 2017 + the replaced closed-case history into the running graph.

Upsert-only: Round 1 vertices stay, January rows are added, ClosedCase rows are
re-loaded from the final-round file (5,585). NEXT edges bridge each card's last
December txn to its first January txn. p_fraud comes from data/stage/r2/scores_r2.parquet
when it exists (B1), else -1 (= not scored), and can be re-run after B1 lands.

    python -m assay.r2.tg_load prepare
    python -m assay.r2.tg_load load
"""

from __future__ import annotations

import subprocess
import sys

import pandas as pd

from assay.data import DATA, ROOT
from assay.r2.frames import R2_STAGE, closed_cases, tx_all
from assay.tg import CONTAINER, device_id, gsql_file

OUT = DATA / "tg_r2"


def prepare() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    t = tx_all()
    sc_path = R2_STAGE / "scores_r2.parquet"
    pf = pd.read_parquet(sc_path).set_index("TransactionID").p_fraud if sc_path.exists() else pd.Series(dtype=float)
    jan = t[t.month_src == "jan"].copy()
    jan["p_fraud"] = jan.TransactionID.map(pf).fillna(-1).round(5)
    out = pd.DataFrame({
        "txn_id": jan.TransactionID.astype(str), "ts": jan.t.dt.strftime("%Y-%m-%d %H:%M:%S"), "amount": jan.amount,
        "product": jan.ProductCD, "channel": jan.channel,
        "addr1": jan.addr1.fillna(-1).astype(int), "dist1": jan.dist1.fillna(-1),
        "p_email": jan.P_emaildomain.fillna(""), "r_email": jan.R_emaildomain.fillna(""),
        "risk_score": jan.risk_score, "p_fraud": jan.p_fraud,
        "id_15": jan.id_15.fillna(""), "id_23": jan.id_23.fillna(""), "device_type": jan.DeviceType.fillna(""),
        "device_info": jan.DeviceInfo.fillna(""), "os": jan.id_30.fillna(""), "browser": jan.id_31.fillna(""),
        "screen": jan.id_33.fillna(""), "device_profile": jan.device_profile,
        "m4": jan.M4.fillna(""), "m5": jan.M5.fillna(""), "m6": jan.M6.fillna(""),
        "d1": jan.D1.fillna(-1), "c1": jan.C1.fillna(-1),
        "card_id": jan.card_id, "customer_id": jan.customer_id, "holder_id": jan.uid,
    })
    out["device_id"] = [device_id(p) for p in out.device_profile]
    out.to_csv(OUT / "txn.csv", index=False)

    card = jan.groupby("card_id").agg(customer_id=("customer_id", "first"), card_type=("card6", "first"),
                                      network=("card4", "first")).reset_index().fillna("")
    card.to_csv(OUT / "card.csv", index=False)

    # device counts are recomputed over Jul-Jan so n_cards stays right for shared devices
    allp = t[t.device_profile != ""]
    d = allp.groupby("device_profile").agg(n_cards=("card_id", "nunique"), n_txns=("TransactionID", "size")).reset_index()
    d = d[d.device_profile.isin(set(out.device_profile))]
    d.insert(0, "device_id", [device_id(p) for p in d.device_profile])
    d.rename(columns={"device_profile": "profile"}).to_csv(OUT / "device.csv", index=False)

    s = t.sort_values(["card_id", "t"], kind="stable")[["card_id", "TransactionID", "TransactionDT", "month_src"]]
    same = s.card_id.values[:-1] == s.card_id.values[1:]
    into_jan = s.month_src.values[1:] == "jan"
    nxt = pd.DataFrame({"src": s.TransactionID.astype(str).values[:-1], "dst": s.TransactionID.astype(str).values[1:],
                        "gap_seconds": (s.TransactionDT.values[1:] - s.TransactionDT.values[:-1]).astype(int)})
    nxt[same & into_jan].to_csv(OUT / "next.csv", index=False)

    cc = closed_cases()
    c = cc.drop(columns=["txn_list", "connected_list"]).copy()
    c["first_fraud_txn_id"] = c.first_fraud_txn_id.map(lambda x: "" if pd.isna(x) else str(int(x)))
    c.fillna("").to_csv(OUT / "closed_case.csv", index=False)
    pd.DataFrame([(r.case_id, str(x)) for r in cc.itertuples() for x in r.txn_list],
                 columns=["case_id", "txn_id"]).to_csv(OUT / "closed_case_txn.csv", index=False)
    pd.DataFrame([(r.case_id, k) for r in cc.itertuples() for k in r.connected_list],
                 columns=["case_id", "card_id"]).to_csv(OUT / "closed_case_connected.csv", index=False)
    print(f"prepared {len(out):,} jan txns, {len(card):,} cards, {len(d):,} devices, {(same & into_jan).sum():,} bridge edges, {len(c):,} closed cases")


def load() -> None:
    src = (ROOT / "graph" / "load.gsql").read_text()
    job = (src.replace("load_assay", "load_assay_r2").replace("/home/tigergraph/data/tg/", "/home/tigergraph/data/tg_r2/"))
    p = ROOT / "graph" / "load_r2.gsql"
    p.write_text("// Generated by assay/r2/tg_load.py from load.gsql: same job, January files.\n" + job)
    print(gsql_file(p)[-2500:])


if __name__ == "__main__":
    {"prepare": prepare, "load": load}[sys.argv[1]]()
