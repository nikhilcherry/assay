"""What the shipped agent actually does on the 18 exam cases, read from a live run.

    python -m assay.r2.factsheet          # -> docs/r2/FACTS.json + docs/r2/FACTS.md

The write-ups (RESILIENCE.md, INNOVATION.md) quote this file, not the block reports:
a block report measures a detector on its own, while this records which detectors
fired inside a real investigation, with the likelihood ratio the ledger used.
"""

from __future__ import annotations

import json
import sys

from assay.data import ROOT
from assay.r2.frames import case_pack
from assay.r2.investigate_r2 import ENABLED, R2Investigator
from assay.r2.store_r2 import R2LocalStore, case_writer, r2_pattern_model

OUT = ROOT / "docs" / "r2"


def _wrap(det, log: list):
    run = det.run

    def recorded(ctx):
        out = list(run(ctx))
        for fd in out:
            log.append({
                "detector": getattr(fd, "detector", type(det).__name__),
                "kind": getattr(fd, "kind", "evidence"),
                "lr": round(float(fd.lr), 4),
                "pattern": fd.pattern,
                "connected_cards": len(fd.connected_card_ids or []),
                "affected_txns": len(fd.affected_txn_ids or []),
                "what": fd.claim.what[:240],
            })
        return out

    det.run = recorded


def collect() -> dict:
    store = R2LocalStore()
    inv = R2Investigator(store, r2_pattern_model(), writer=case_writer(store))
    log: list = []
    for det in inv.detectors:
        _wrap(det, log)
    cases = []
    for _, case in case_pack().iterrows():
        log.clear()
        store.memory.clear()   # each case starts fresh, as `python -m assay.r2.agent <case>` does
        ans = inv.run(case)
        c = ans["case"]
        cases.append({
            "case_id": case.case_id,
            "trigger_type": case.trigger_type,
            "verdict": c["verdict"],
            "fraud_probability": c["fraud_probability"],
            "pattern": c["pattern"],
            "exposure_usd": c["exposure_usd"],
            "affected_txns": len(c["affected_txn_ids"]),
            "connected_cards": len(c["connected_card_ids"]),
            "sar": ans["sar"]["file"],
            "similar_prior_cases": len(c["similar_prior_cases"]),
            "final_actions": [x["action"] for x in ans["next_best_actions"]["final"]],
            "card_mismatch": bool(inv._card_mismatch),
            "findings": list(log),
        })
    cases.sort(key=lambda c: c["case_id"])
    fired = {}
    for c in cases:
        for fd in c["findings"]:
            if fd["kind"] != "context":
                fired.setdefault(fd["detector"], []).append(c["case_id"])
    return {"enabled": ENABLED, "fired_on": {k: sorted(set(v)) for k, v in sorted(fired.items())},
            "verdicts": {v: sum(c["verdict"] == v for c in cases) for v in ("fraud", "uncertain", "legitimate")},
            "cases": cases}


def to_markdown(f: dict) -> str:
    lines = ["# Fact sheet: the shipped agent on the 18 exam cases", "",
             "Generated by `python -m assay.r2.factsheet` from a live run; do not edit by hand.", "",
             f"Verdicts: {f['verdicts']['fraud']} fraud, {f['verdicts']['uncertain']} uncertain, "
             f"{f['verdicts']['legitimate']} legitimate. Enabled detectors: {', '.join(f['enabled'])}.", "",
             "## Which detector fired where", "", "| detector | cases (weighed evidence) |", "|---|---|"]
    for det in f["enabled"] + sorted(set(f["fired_on"]) - set(f["enabled"])):
        hit = [k for k in f["fired_on"] if k.lower() == det.lower()]
        lines.append(f"| {det} | {', '.join(f['fired_on'][hit[0]]) if hit else 'none'} |")
    mm = [c["case_id"] for c in f["cases"] if c["card_mismatch"]]
    lines += ["", f"Case-pack card differs from the bank's record (DQ-07, never cleared): {', '.join(mm) or 'none'}."]
    lines += ["", "## Per case", "",
              "| case | verdict | p | pattern | exposure | conn | SAR | findings (detector, LR) |",
              "|---|---|---|---|---|---|---|---|"]
    for c in f["cases"]:
        fds = "; ".join(f"{x['detector']} {x['lr']:g}" + (" (context)" if x["kind"] == "context" else "")
                        for x in c["findings"]) or "none"
        lines.append(f"| {c['case_id']} | {c['verdict']} | {c['fraud_probability']:.2f} | {c['pattern']} | "
                     f"${c['exposure_usd']:,.2f} | {c['connected_cards']} | {c['sar']} | {fds} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    f = collect()
    (OUT / "FACTS.json").write_text(json.dumps(f, indent=2) + "\n")
    (OUT / "FACTS.md").write_text(to_markdown(f))
    print(to_markdown(f))
    return 0


if __name__ == "__main__":
    sys.exit(main())
