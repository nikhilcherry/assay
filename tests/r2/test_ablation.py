"""Tests for BLOCK C1 -- Leave-one-out ablation of the shipped agent."""

from __future__ import annotations

import json

from assay import disputes
from assay.data import ROOT
from assay.r2 import ablation
from assay.r2 import dispute_episode
from assay.r2 import investigate_r2
from assay.r2.frames import case_pack


def test_ablation_full_reproduces_shipped_cases_and_restores_state():
    """1. Verify `full` reproduces `cases_r2/HHF-*.json` verdict, fraud_probability, and final actions for all 18 cases.
    2. Run all ablation configs and print the markdown matrix.
    3. Verify module state is cleanly restored after running every config by running `full` again at the end.
    """
    cp = case_pack().sort_values("case_id")
    assert len(cp) == 18

    # Snapshot initial module attributes before any ablation runs
    orig_enabled = list(investigate_r2.ENABLED)
    orig_trained_until = investigate_r2.MODEL_TRAINED_UNTIL
    orig_model_trusted = investigate_r2.R2Investigator.model_trusted
    orig_extra_findings = investigate_r2.R2Investigator._extra_findings
    orig_assumed_clear = investigate_r2.R2Investigator.assumed_clear_allowed
    orig_ep_fn = dispute_episode.episode_for_dispute
    orig_ep_cap = dispute_episode.EPISODE_CAP_HOURS
    orig_w_override = disputes.W_OVERRIDE
    orig_measured_w_fn = investigate_r2.measured_exam_dispute_weight

    # Run all configs (including initial "full")
    all_runs, diffs = ablation.run_all_ablations()
    full_initial = all_runs["full"]
    assert len(full_initial) == 18

    # Check that "full" reproduces cases_r2/*.json for all 18 cases
    cases_dir = ROOT / "cases_r2"
    mismatches: list[str] = []
    for cid, outcome in sorted(full_initial.items()):
        ans_path = cases_dir / f"{cid}.json"
        assert ans_path.exists(), f"Missing shipped answer file: {ans_path}"
        shipped = json.loads(ans_path.read_text(encoding="utf-8"))
        s_case = shipped["case"]
        s_verdict = s_case["verdict"]
        s_p = round(float(s_case["fraud_probability"]), 2)
        s_actions = tuple(x["action"] for x in shipped["next_best_actions"]["final"])
        s_sar = bool(shipped["sar"]["file"])
        s_exp = round(float(s_case["exposure_usd"]), 2)
        s_conn = len(s_case.get("connected_card_ids", []))
        s_pat = s_case["pattern"]

        if (
            outcome.verdict != s_verdict
            or outcome.fraud_probability != s_p
            or outcome.final_actions != s_actions
            or outcome.sar_filed != s_sar
            or outcome.exposure_usd != s_exp
            or outcome.connected_card_ids_count != s_conn
            or outcome.pattern != s_pat
        ):
            mismatches.append(
                f"{cid}: full={outcome.to_dict()} vs cases_r2={{'verdict': {s_verdict!r}, 'p': {s_p}, "
                f"'pattern': {s_pat!r}, 'exposure_usd': {s_exp}, 'conn': {s_conn}, 'sar': {s_sar}, "
                f"'actions': {list(s_actions)}}}"
            )

    if mismatches:
        diff_msg = "\n".join(mismatches)
        print("MISMATCHES BETWEEN `full` AND `cases_r2/*.json`:\n" + diff_msg)
        raise AssertionError(f"`full` config did not reproduce `cases_r2/*.json`:\n{diff_msg}")

    # Verify every detector in investigate_r2.ENABLED has a corresponding config
    for det in orig_enabled:
        assert f"no_{det}" in all_runs, f"Missing ablation config for detector {det}"
        assert len(all_runs[f"no_{det}"]) == 18

    # Verify module attributes were restored after all configs ran
    assert investigate_r2.ENABLED == orig_enabled
    assert investigate_r2.MODEL_TRAINED_UNTIL == orig_trained_until
    assert investigate_r2.R2Investigator.model_trusted is orig_model_trusted
    assert investigate_r2.R2Investigator._extra_findings is orig_extra_findings
    assert investigate_r2.R2Investigator.assumed_clear_allowed is orig_assumed_clear
    assert dispute_episode.episode_for_dispute is orig_ep_fn
    assert dispute_episode.EPISODE_CAP_HOURS == orig_ep_cap
    assert disputes.W_OVERRIDE == orig_w_override
    assert investigate_r2.measured_exam_dispute_weight is orig_measured_w_fn

    # Run "full" again at the end and compare to initial "full"
    full_after = ablation.run_config("full")
    after_diff = ablation.diff(full_initial, full_after, config_name="full_after")
    assert after_diff.n_changed_cases == 0, f"State leaked across configs: {after_diff.per_case_changes}"
    assert full_after == full_initial

    # Format, write, and print the markdown matrix
    md = ablation.format_markdown_report(all_runs, diffs)
    ablation.OUT_DOC.write_text(md, encoding="utf-8")
    print("\n" + md)

    assert ablation.OUT_DOC.exists()
    doc_text = ablation.OUT_DOC.read_text(encoding="utf-8")
    assert "Generated by `python -m assay.r2.ablation`; do not edit." in doc_text
    assert "$ exposure no longer acted on" in doc_text
    assert "new hard actions" in doc_text
